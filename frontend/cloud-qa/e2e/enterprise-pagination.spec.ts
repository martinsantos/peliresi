import { test,expect } from '@playwright/test';
import { login,prefix } from './helpers';
test('company pagination and search preserve unsaved work and load the selected company context beyond page one',async({page},info)=>{
 const errors:string[]=[],consoleMessages:string[]=[];
 page.on('pageerror',e=>errors.push(e.message));page.on('console',m=>{if(['error','warning'].includes(m.type()))consoleMessages.push(m.text());});
 await login(page,info,'empresa-'+info.project.name+'-owner');
 await page.goto('http://127.0.0.1:4177'+prefix(info)+'/empresas');
 await expect(page.getByRole('heading',{name:'Empresas y establecimientos',exact:true})).toBeVisible();
 const company=page.getByLabel('Empresa',{exact:true}),legal=page.getByLabel('Calle legal',{exact:true});
 await expect(legal).toHaveValue(new RegExp('^Legal QA (100|'+info.project.name+' 101)$'));
 await legal.fill('Borrador que no debe perderse');
 await page.getByRole('button',{name:'Siguiente',exact:true}).click();
 await expect(page.getByRole('status').filter({hasText:'26–50 de 211 empresas'})).toBeVisible();
 await expect(legal).toHaveValue('Borrador que no debe perderse');
 await expect(company).toContainText('QA Empresa '+info.project.name);
 expect(await company.locator('option').count()).toBeLessThanOrEqual(26);
 const search=page.getByLabel('Buscar empresa',{exact:true});
 await search.fill('QA Paginación 210');await page.getByRole('button',{name:'Buscar',exact:true}).click();
 await expect(page.getByRole('status').filter({hasText:'1–1 de 1 empresas'})).toBeVisible();
 await expect(legal).toHaveValue('Borrador que no debe perderse');
 const lastId=await company.locator('option').filter({hasText:'QA Paginación 210'}).getAttribute('value');
 expect(lastId).toBeTruthy();await company.selectOption(lastId!);
 await expect(legal).toHaveValue('Legal paginación 210');
 await expect(page.getByLabel('Actividad autorizada',{exact:true})).toContainText('Generador');
 await search.fill('Ninguna coincidencia QA');await page.getByRole('button',{name:'Buscar',exact:true}).click();
 await expect(page.getByText('Sin coincidencias',{exact:true})).toBeVisible();
 await expect(legal).toHaveValue('Legal paginación 210');
 await expect(company.locator('option')).toHaveCount(1);
 await page.getByRole('button',{name:'Limpiar búsqueda',exact:true}).click();
 await expect(page.getByRole('status').filter({hasText:'1–25 de 211 empresas'})).toBeVisible();
 await expect(legal).toHaveValue('Legal paginación 210');
 expect(await page.evaluate(()=>document.documentElement.scrollWidth-innerWidth)).toBeLessThanOrEqual(1);
 expect(await page.title()).toMatch(/SITREP/i);expect((await page.locator('#root').innerText()).length).toBeGreaterThan(20);
 await expect(page.locator('vite-error-overlay,nextjs-portal')).toHaveCount(0);
 expect(errors).toEqual([]);expect(consoleMessages).toEqual([]);
 await page.screenshot({path:info.outputPath('company-pagination.png'),fullPage:true});
 await info.attach('pagination-proof',{body:Buffer.from(JSON.stringify({url:page.url(),title:await page.title(),console:consoleMessages,errors})),contentType:'application/json'});
});
