import { test, expect } from '@playwright/test';
import { randomUUID } from 'node:crypto';
import { assertCloudDatabase } from '../safety';
import { login, prefix } from './helpers';

test.beforeAll(async () => { await assertCloudDatabase(); });

test('an administrator must enter the travel threshold and can save a draft', async ({ page }, info) => {
  const errors: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  await login(page, info, 'admin');
  if (info.project.name === 'app') await page.setViewportSize({ width: 320, height: 800 });
  await page.goto(prefix(info) + '/alertas');
  await page.getByRole('tab', { name: /Reglas/ }).click();
  await page.getByRole('button', { name: 'Nueva Regla', exact: true }).click();
  const dialog = page.getByRole('dialog', { name: 'Nueva Regla', exact: true });
  const name = 'QA duración ' + info.project.name + ' ' + randomUUID().slice(0, 8);
  await dialog.getByLabel('Nombre', { exact: true }).fill(name);
  await dialog.getByRole('button', { name: 'Evento', exact: true }).click();
  await page.getByRole('option', { name: 'Duración del viaje', exact: true }).click();
  const hours = dialog.getByLabel('Avisar a partir de (horas)');
  await expect(hours).toHaveValue('');
  await expect(dialog.getByText(/sin ubicaciones nuevas no se genera el aviso/i)).toBeVisible();
  await dialog.getByRole('checkbox', { name: /ADMIN Administración central/ }).check();
  const rejected = page.waitForResponse(response => response.url().endsWith('/api/alertas/reglas') && response.request().method() === 'POST');
  await dialog.getByRole('button', { name: 'Crear regla', exact: true }).click();
  expect((await rejected).status()).toBe(400);
  const alert = dialog.getByRole('alert');
  await expect(alert).toContainText('umbral');
  await expect(alert).toBeFocused();
  await expect(dialog.getByLabel('Nombre', { exact: true })).toHaveValue(name);
  await alert.screenshot({ path: info.outputPath('umbral-faltante.png') });
  await hours.fill('36');
  await dialog.getByLabel('Regla activa').uncheck();
  const created = page.waitForResponse(response => response.url().endsWith('/api/alertas/reglas') && response.request().method() === 'POST');
  await dialog.getByRole('button', { name: 'Crear regla', exact: true }).click();
  const response = await created;
  expect(response.status()).toBe(201);
  const rule = (await response.json()).data;
  expect(rule.activa).toBe(false); expect(JSON.parse(rule.condicion)).toEqual({ horasTransito: { gte: 36 } });
  await expect(dialog).toHaveCount(0);
  const edit = page.getByRole('button', { name: `Editar regla: ${name}`, exact: true });
  await expect(edit).toBeVisible();
  const rowText = await edit.evaluate(element => (element.closest('tr') || element.closest('div.bg-white'))?.textContent || '');
  expect(rowText).toContain('Duración del viaje');
  expect(rowText).not.toContain('TIEMPO_EXCESIVO');
  expect(await page.evaluate(() => document.documentElement.scrollWidth - innerWidth)).toBeLessThanOrEqual(1);
  await page.screenshot({ path: info.outputPath('regla-borrador.png'), animations: 'disabled', fullPage: true });
  expect(errors).toEqual([]);
});
